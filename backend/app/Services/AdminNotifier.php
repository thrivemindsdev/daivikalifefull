<?php

namespace App\Services;

use App\Models\Notification;
use App\Models\User;
use Illuminate\Support\Facades\Mail;
use Illuminate\Mail\Message;

// Notifies every admin: a dashboard notification (+ web push) and an email alert when SMTP is configured.
// Runs after the response has been sent, so it never slows down or breaks the request that triggered it.
class AdminNotifier
{
    public static function notify(string $title, string $message, string $type = 'general', string $link = ''): void
    {
        app()->terminating(function () use ($title, $message, $type, $link) {
            self::run($title, $message, $type, $link);
        });
    }

    public static function run(string $title, string $message, string $type = 'general', string $link = ''): void
    {
        try {
            $adminIds = User::query()->where('role', 'admin')->pluck('id')->all();
            foreach ($adminIds as $adminId) {
                Notification::query()->create([
                    'targetUserId' => $adminId,
                    'title' => $title,
                    'message' => $message,
                    'type' => $type,
                    'link' => $link,
                    'isRead' => false,
                ]);
                if (WebPushService::configured()) {
                    try {
                        WebPushService::send($adminId, $title, $message, $link ?: '/');
                    } catch (\Throwable $e) {
                        logger()->warning('Admin push failed: '.$e->getMessage());
                    }
                }
            }
        } catch (\Throwable $e) {
            logger()->error('Notifier: failed to save admin notifications: '.$e->getMessage());
        }

        self::email($title, $message, $type);
    }

    private static function email(string $title, string $message, string $type): void
    {
        $user = (string) config('daivika.smtp.user');
        $pass = (string) config('daivika.smtp.pass');
        if ($user === '' || $pass === '') {
            return;
        }
        $port = (int) config('daivika.smtp.port', 587);
        $recipient = (string) config('daivika.smtp.admin_email');

        [$color, $label] = match ($type) {
            'new_order' => ['#10B981', 'New Store Order 🛍️'],
            'new_review' => ['#3B82F6', 'Customer Review ⭐'],
            'new_lead' => ['#F59E0B', 'Inbox Inquiry 💬'],
            'new_subscriber' => ['#8B5CF6', 'Newsletter Subscription 📧'],
            default => ['#8b5e3c', 'System Alert'],
        };
        $dashboardUrl = rtrim((string) config('daivika.frontend_url'), '/').'/admin/dashboard';
        $e = fn ($s) => htmlspecialchars((string) $s, ENT_QUOTES, 'UTF-8');

        $html = <<<HTML
<div style="font-family: 'Poppins', 'Helvetica Neue', Helvetica, Arial, sans-serif; background-color: #f3f4f6; padding: 2rem 0; width: 100%; margin: 0;">
  <table align="center" border="0" cellpadding="0" cellspacing="0" width="600" style="background-color: #ffffff; border-collapse: collapse; border-radius: 12px; overflow: hidden; box-shadow: 0 4px 6px rgba(0, 0, 0, 0.05);">
    <tr>
      <td bgcolor="#000000" style="padding: 2.5rem 2rem; text-align: center;">
        <h1 style="color: #ffffff; font-size: 1.5rem; font-weight: 700; margin: 0; letter-spacing: 1px;">DAIVIKA</h1>
        <p style="color: #a3a3a3; font-size: 0.75rem; margin: 0.25rem 0 0 0; text-transform: uppercase; letter-spacing: 2px;">Daivika Store Admin</p>
      </td>
    </tr>
    <tr>
      <td style="padding: 2.5rem 2.5rem 1.5rem 2.5rem;">
        <div style="display: inline-block; padding: 0.35rem 0.85rem; background-color: {$color}; color: #ffffff; font-size: 0.7rem; font-weight: 700; border-radius: 50px; text-transform: uppercase; margin-bottom: 1.25rem; letter-spacing: 0.5px;">{$label}</div>
        <h2 style="color: #111827; font-size: 1.25rem; font-weight: 700; margin: 0 0 0.75rem 0; line-height: 1.3;">{$e($title)}</h2>
        <p style="color: #4b5563; font-size: 0.95rem; line-height: 1.6; margin: 0 0 2rem 0;">{$e($message)}</p>
        <table border="0" cellpadding="0" cellspacing="0" width="100%" style="margin: 2rem 0;">
          <tr>
            <td align="center">
              <a href="{$e($dashboardUrl)}" style="background-color: #8b5e3c; color: #ffffff; text-decoration: none; padding: 0.85rem 2rem; border-radius: 8px; font-size: 0.9rem; font-weight: 600; display: inline-block;">Open Admin Control Panel</a>
            </td>
          </tr>
        </table>
      </td>
    </tr>
    <tr>
      <td bgcolor="#f9fafb" style="padding: 1.5rem; border-top: 1px solid #f3f4f6; text-align: center; color: #9ca3af; font-size: 0.75rem;">
        This is an automated alert generated by the Daivika Portal.<br/>
        Configured Admin Recipient: <span style="font-weight: 600; color: #6b7280;">{$e($recipient)}</span>
      </td>
    </tr>
  </table>
</div>
HTML;

        try {
            config([
                'mail.mailers.daivika_smtp' => [
                    'transport' => 'smtp',
                    'host' => config('daivika.smtp.host') ?: 'smtp.gmail.com',
                    'port' => $port,
                    'scheme' => $port === 465 ? 'smtps' : 'smtp',
                    'username' => $user,
                    'password' => $pass,
                    'timeout' => 20,
                ],
            ]);
            Mail::mailer('daivika_smtp')->html($html, function (Message $mail) use ($user, $recipient, $title) {
                $mail->from($user, 'Daivika Notifications')->to($recipient)->subject("🔔 Admin Alert: $title");
            });
        } catch (\Throwable $e) {
            logger()->error('Notifier: failed to deliver email notification: '.$e->getMessage());
        }
    }
}
