export const INDIAN_STATES = Object.keys(INDIA_DISTRICTS);

export const getDistricts = (state) => (INDIA_DISTRICTS[state] || []).map(d => d[0]);

const normalize = (s) => (s || '').toString().toLowerCase().replace(/[^a-z0-9]/g, '');

export const findState = (state) => {
  const key = normalize(state);
  if (!key) return null;
  return INDIAN_STATES.find(s => normalize(s) === key) || null;
};

// Matches "Ahmednagar" to "Ahilyanagar (Ahmednagar)" as well as the exact name
const districtMatches = (name, key) => {
  if (normalize(name) === key) return true;
  const m = name.match(/^(.*?)\s*\((.*)\)$/);
  return !!m && (normalize(m[1]) === key || normalize(m[2]) === key);
};

// Returns { state, name, lat, lng } for a state + district pair (lenient matching), or null
export const findDistrict = (state, district) => {
  const key = normalize(district);
  if (!key) return null;
  const st = findState(state);
  for (const s of st ? [st] : INDIAN_STATES) {
    const hit = INDIA_DISTRICTS[s].find(d => districtMatches(d[0], key));
    if (hit) return { state: s, name: hit[0], lat: hit[1], lng: hit[2] };
  }
  return null;
};

// Great-circle distance in km between two { lat, lng } points
export const distanceKm = (a, b) => {
  if (!a || !b) return Infinity;
  const R = 6371;
  const toRad = (x) => (x * Math.PI) / 180;
  const dLat = toRad(b.lat - a.lat);
  const dLng = toRad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(toRad(a.lat)) * Math.cos(toRad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};
